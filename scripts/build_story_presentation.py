def portrait(slide, path: Path, x: float, y: float, w: float, h: float):
    """Crop in the PPTX; keep the original supplied JPEG unchanged."""
    with Image.open(path) as photo:
        iw, ih = photo.size
    shape = slide.shapes.add_picture(str(path), Inches(x), Inches(y), Inches(w), Inches(h))
    source, target = iw / ih, w / h
    if source > target:
        crop = (1 - target / source) / 2
        shape.crop_left = shape.crop_right = crop
    else:
        crop = (1 - source / target) / 2
        shape.crop_top = shape.crop_bottom = crop


