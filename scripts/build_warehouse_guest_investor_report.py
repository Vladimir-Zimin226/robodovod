def sha(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def load_verified_package() -> tuple[dict, str]:
    manifest_bytes = (SOURCE / "manifest.json").read_bytes()
    manifest = json.loads(manifest_bytes)
    with zipfile.ZipFile(io.BytesIO((SOURCE / "evidence.zip").read_bytes())) as archive:
        if archive.read("manifest.json") != manifest_bytes:
            raise ValueError("guest archive manifest mismatch")
        for name, meta in manifest["files"].items():
            content = archive.read(name)
            if sha(content) != meta["sha256"] or len(content) != meta["bytes"]:
                raise ValueError(f"guest archive integrity mismatch: {name}")
        payload = archive.read("package.json")
        if payload != PAGE_PACKAGE.read_bytes() or archive.read("report.pdf") != (SOURCE / "report.pdf").read_bytes():
            raise ValueError("guest page/download source mismatch")
    package = json.loads(payload)
    if package["schema_version"] != "warehouse-pallet-demo-v2" or package["bindings"] != manifest["bindings"]:
        raise ValueError("unsupported guest source or bindings")
    return package, sha(payload)


