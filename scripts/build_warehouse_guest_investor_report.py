def expected_files() -> dict[Path, bytes]:
    package, source_digest = load_verified_package()
    pdf = report_bytes(package)
    manifest = {"schema_version": "guest-investor-presentation-v1", "presentation_version": VERSION,
                "depth": "FULL_AUTHORED_EXAMPLE", "source_package_digest": source_digest,
                "bindings": package["bindings"], "files": {"report.pdf": {"sha256": sha(pdf), "bytes": len(pdf)}}}
    return {TARGET / "report.pdf": pdf, TARGET / "manifest.json": (json.dumps(manifest, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = expected_files()
    if args.check:
        return int(any(not p.is_file() or p.read_bytes() != body for p, body in files.items()))
    TARGET.mkdir(parents=True, exist_ok=True)
    for path, body in files.items():
        path.write_bytes(body)
        print(f"{path.relative_to(ROOT)}: {len(body)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
